  /* ----- quiz ----- */
  function quizCard(L){
    const card = h('div.card.pad.tj-quiz');
    const intro = ()=>{
      card.replaceChildren(h('div.tj-rh', h('i.tj-dot.tj-c-base'), h('b.title-font', 'اختبر نفسك')),
        h('p.tj-d', 'ثلاثة أسئلة قصيرة على هذا الدرس. تحصل على نجمة عن كل إجابة صحيحة، ويُحفظ أفضل ناتج لك.'),
        h('div.row-flex', h('span.small.muted', 'أفضل نتيجة:'), starsEl(bestOf(L.id), true)),
        h('button.btn.block', {style:'margin-top:12px', onclick:()=>run()}, bestOf(L.id) ? 'أعد الاختبار' : 'ابدأ الاختبار'));
    };
    const run = ()=>{
      const qs = shuffle(L.quiz); let i = 0, score = 0;
      const step = ()=>{
        if(i >= qs.length){ finish(); return; }
        const q = qs[i], opts = shuffle(q.a.map((t, k)=>({t, ok:k === 0}))); let done = false;
        const fb = h('div.tj-fb'), next = h('button.btn.block', {style:'display:none;margin-top:10px', onclick:()=>{ i++; step(); }}, i === qs.length - 1 ? 'عرض النتيجة' : 'السؤال التالي');
        const list = h('div.tj-opts', ...opts.map(o=>{
          const b = h('button.tj-opt', {onclick:()=>{
            if(done) return; done = true;
            if(o.ok) score++;
            list.querySelectorAll('.tj-opt').forEach((x, k)=>{ x.disabled = true; if(opts[k].ok) x.classList.add('ok'); });
            if(!o.ok) b.classList.add('bad');
            fb.replaceChildren(h('b', o.ok ? 'أحسنت!' : 'ليست الإجابة الصحيحة.'), h('span', ' '+q.why));
            fb.classList.add(o.ok ? 'ok' : 'bad'); next.style.display = '';
            M.haptic && M.haptic(o.ok ? 12 : 30);
          }}, o.t);
          return b;
        }));
        card.replaceChildren(h('div.tj-qh', h('b.title-font', 'السؤال '+M.n(i + 1)+' من '+M.n(qs.length)), h('div.bar.tj-qbar', h('i', {style:'width:'+(i / qs.length * 100)+'%'}))),
          h('p.tj-q', q.q), list, fb, next);
      };
      const finish = ()=>{
        const p = prog(), old = p[L.id] || {}, best = Math.max(old.best || 0, score);
        p[L.id] = {best, tries:(old.tries || 0) + 1, last:score};
        M.store.set('tj:prog', p); refreshTop();
        card.replaceChildren(h('div.center', h('div.title-font.bold', score === qs.length ? 'ما شاء الله! نتيجة كاملة' : score ? 'نتيجة جيدة' : 'حاول مرة أخرى'),
          starsEl(score, true), h('p.tj-d', M.n(score)+' من '+M.n(qs.length)+' إجابات صحيحة'),
          h('div.row-flex', {style:'justify-content:center;gap:8px'}, h('button.btn.tonal', {onclick:()=>run()}, 'أعد الاختبار'), h('button.btn', {onclick:()=>{ const idx = LESSONS.findIndex(x=>x.id === L.id); go(idx + 1 < LESSONS.length ? LESSONS[idx + 1].id : 'home'); }}, 'الدرس التالي'))));
      };
      step();
    };
    intro();
    return card;
  }

