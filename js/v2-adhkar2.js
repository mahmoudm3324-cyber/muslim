function moment(){
  const d = new Date(), hr = d.getHours(), fri = d.getDay() === 5;
  let cat, why;
  if(fri && hr >= 9 && hr < 19){ cat = 'salawat'; why = 'يوم الجمعة — أكثِر من الصلاة على النبي ﷺ'; }
  else if(hr >= 3 && hr < 6){ cat = 'istighfar'; why = 'وقت السحر — وقت الاستغفار'; }
  else if(hr >= 6 && hr < 11){ cat = 'ilm'; why = 'بداية اليوم — سؤال العلم النافع والرزق'; }
  else if(hr >= 11 && hr < 15){ cat = 'tasbih'; why = 'وسط النهار — اغتنم لحظة بتسبيحة'; }
  else if(hr >= 15 && hr < 18){ cat = 'salawat'; why = 'العصر — الصلاة على النبي ﷺ'; }
  else if(hr >= 18 && hr < 21){ cat = 'jawami'; why = 'المساء — جوامع الدعاء'; }
  else if(hr >= 21){ cat = 'sleep'; why = 'قبل النوم — أذكار الفراش'; }
  else { cat = 'jawami'; why = 'جوف الليل — وقت قبول الدعاء'; }
  const c = catsOf().find(x=>x.id === cat) || catsOf()[0];
  const seed = Math.floor(d.getTime() / 36e5) + Math.floor(d.getTime() / 864e5);
  const pool = c.items.filter(i=>i.t && i.t.length < 260); const items = pool.length ? pool : c.items;
  return {cat:c, it:items[seed % items.length], why};
}

